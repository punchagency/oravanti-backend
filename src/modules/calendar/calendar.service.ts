export const createCalendarEvent = async (
  organizationId: string,
  data: Omit<
    NewCalendarEvent,
    | "id"
    | "organizationId"
    | "createdAt"
    | "updatedAt"
    | "isAutoGenerated"
    | "parentEventId"
  >,
) => {
  const [event] = await db
    .insert(calendarEvents)
    .values({ ...data, organizationId, isAutoGenerated: false })
    .returning();

  await insertDeadlines(event);

  return fetchEventWithJoins(event.id, organizationId);
};

export const updateCalendarEvent = async (
  id: string,
  organizationId: string,
  data: Partial<NewCalendarEvent>,
) => {
  const [existing] = await db
    .select({ status: calendarEvents.status })
    .from(calendarEvents)
    .where(
      and(
        eq(calendarEvents.id, id),
        eq(calendarEvents.organizationId, organizationId),
      ),
    )
    .limit(1);

  if (!existing) return null;
  if (existing.status === "completed" || existing.status === "cancelled") {
    throw new Error(
      `Cannot update a ${existing.status} event`,
    );
  }

  const [updated] = await db
    .update(calendarEvents)
    .set({ ...data, updatedAt: new Date() })
    .where(
      and(
        eq(calendarEvents.id, id),
        eq(calendarEvents.organizationId, organizationId),
      ),
    )
    .returning();

  if (!updated) return null;

  const isHearing =
    updated.eventType === "master_calendar_hearing" ||
    updated.eventType === "individual_hearing";

  if (isHearing && data.startTime) {
    await deleteAutoGeneratedChildren(id);
    await insertDeadlines(updated);
  }

  return fetchEventWithJoins(id, organizationId);
};

export const deleteCalendarEvent = async (
  id: string,
  organizationId: string,
): Promise<void> => {
  const [existing] = await db
    .select({ status: calendarEvents.status })
    .from(calendarEvents)
    .where(
      and(
        eq(calendarEvents.id, id),
        eq(calendarEvents.organizationId, organizationId),
      ),
    )
    .limit(1);

  if (!existing) return;
  if (existing.status === "completed" || existing.status === "cancelled") {
    throw new Error(
      `Cannot delete a ${existing.status} event`,
    );
  }

  await deleteAutoGeneratedChildren(id);
  await db
    .delete(calendarEvents)
    .where(
      and(
        eq(calendarEvents.id, id),
        eq(calendarEvents.organizationId, organizationId),
      ),
    );
};

// ─── Dashboard Strip ──────────────────────────────────────────────────────────

export const getCalendarStrip = async (
  organizationId: string,
  teamId?: string,
) => {
  // Bucket the 14-day strip against the firm's local calendar days.
  const tz = await getFirmTimezone(organizationId);
  const startDay = dayjs().tz(tz).startOf("day");
  const today = startDay.utc().toDate();
  const end = startDay.add(14, "day").utc().toDate();

  const conditions = [
    eq(calendarEvents.organizationId, organizationId),
    gte(calendarEvents.startTime, today),
    lte(calendarEvents.startTime, end),
  ];
  if (teamId) conditions.push(eq(calendarEvents.teamId, teamId));

  const events = await db
    .select({
      eventType: calendarEvents.eventType,
      startTime: calendarEvents.startTime,
    })
    .from(calendarEvents)
    .where(and(...conditions));

  const days: Record<
    string,
    {
      date: string;
      hearings: number;
      uscisInterviews: number;
      biometrics: number;
      other: number;
      total: number;
    }
  > = {};

  for (let i = 0; i < 14; i++) {
    const key = startDay.add(i, "day").format("YYYY-MM-DD");
    days[key] = {
      date: key,
      hearings: 0,
      uscisInterviews: 0,
      biometrics: 0,
      other: 0,
      total: 0,
    };
  }

  for (const e of events) {
    const key = dayjs.utc(e.startTime).tz(tz).format("YYYY-MM-DD");
    if (!days[key]) continue;
    days[key].total++;
    if (
      e.eventType === "master_calendar_hearing" ||
      e.eventType === "individual_hearing"
    ) {
      days[key].hearings++;
    } else if (e.eventType === "uscis_interview") {
      days[key].uscisInterviews++;
    } else if (e.eventType === "biometric") {
      days[key].biometrics++;
    } else {
      days[key].other++;
    }
  }

  return Object.values(days);
};

