export const getCalendarEvents = async (
  organizationId: string,
  filters?: {
    year?: number;
    month?: number;
    teamId?: string;
    eventTypes?: string[];
  },
) => {
  const conditions = [eq(calendarEvents.organizationId, organizationId)];

  if (filters?.year && filters?.month) {
    const start = new Date(filters.year, filters.month - 1, 1);
    const end = new Date(filters.year, filters.month, 1);
    conditions.push(gte(calendarEvents.startTime, start));
    conditions.push(lte(calendarEvents.startTime, end));
  }

  if (filters?.teamId) {
    conditions.push(eq(calendarEvents.teamId, filters.teamId));
  }

  if (filters?.eventTypes?.length) {
    conditions.push(
      inArray(calendarEvents.eventType, filters.eventTypes as any[]),
    );
  }

  const rows = await db
    .select({
      id: calendarEvents.id,
      eventType: calendarEvents.eventType,
      status: calendarEvents.status,
      title: calendarEvents.title,
      startTime: calendarEvents.startTime,
      endTime: calendarEvents.endTime,
      location: calendarEvents.location,
      zoomLink: calendarEvents.zoomLink,
      notes: calendarEvents.notes,
      isAutoGenerated: calendarEvents.isAutoGenerated,
      parentEventId: calendarEvents.parentEventId,
      teamId: calendarEvents.teamId,
      clientId: clients.id,
      clientDisplayName: clients.displayName,
      caseId: cases.id,
      caseNumber: cases.caseNumber,
      staffId: staff.id,
      staffFirstName: staff.firstName,
      staffLastName: staff.lastName,
      staffRole: staff.jobTitle,
      leadId: leads.id,
      leadFirstName: leads.firstName,
      leadLastName: leads.lastName,
    })
    .from(calendarEvents)
    .leftJoin(clients, eq(clients.id, calendarEvents.clientId))
    .leftJoin(cases, eq(cases.id, calendarEvents.caseId))
    .leftJoin(staff, eq(staff.id, calendarEvents.assignedStaffId))
    .leftJoin(leads, eq(leads.id, calendarEvents.leadId))
    .where(and(...conditions));

  return rows.map((r) => ({
    id: r.id,
    eventType: r.eventType,
    status: r.status,
    title: r.title,
    startTime: r.startTime,
    endTime: r.endTime,
    location: r.location,
    zoomLink: r.zoomLink,
    notes: r.notes,
    isAutoGenerated: r.isAutoGenerated,
    parentEventId: r.parentEventId,
    teamId: r.teamId,
    client: r.clientId
      ? { id: r.clientId, name: r.clientDisplayName ?? "" }
      : null,
    case: r.caseId
      ? { id: r.caseId, caseNumber: r.caseNumber ?? "" }
      : null,
    assignedStaff: r.staffId
      ? {
          id: r.staffId,
          name: `${r.staffFirstName} ${r.staffLastName}`,
          role: r.staffRole,
        }
      : null,
    lead: r.leadId
      ? {
          id: r.leadId,
          name: `${r.leadFirstName} ${r.leadLastName}`,
        }
      : null,
  }));
};

