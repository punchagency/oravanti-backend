// ─── Helpers ─────────────────────────────────────────────────────────────────

const addDays = (d: Date, days: number): Date => {
  const result = new Date(d);
  result.setDate(result.getDate() + days);
  return result;
};

const daysBetween = (a: Date, b: Date): number =>
  Math.floor((b.getTime() - a.getTime()) / (1000 * 60 * 60 * 24));

// ─── Auto-deadline computation ────────────────────────────────────────────────

const buildMCHDeadlines = (event: CalendarEvent): NewCalendarEvent[] => {
  const deadlines: NewCalendarEvent[] = [];
  const hearingDate = new Date(event.startTime);

  if (event.filingSubmittedDate) {
    const filingDate = new Date(event.filingSubmittedDate);
    const diff = daysBetween(filingDate, hearingDate);

    if (diff >= 15) {
      deadlines.push({
        organizationId: event.organizationId,
        eventType: "filing_deadline",
        status: "scheduled",
        title: `Response Deadline — ${event.title}`,
        startTime: addDays(filingDate, 10),
        clientId: event.clientId,
        caseId: event.caseId,
        assignedStaffId: event.assignedStaffId,
        teamId: event.teamId,
        isAutoGenerated: true,
        parentEventId: event.id,
        notes:
          "Auto-generated: response deadline 10 days after filing date (MCH rule)",
      });
    }
    // < 15 days: note already stored on the hearing event — no separate deadline event
  }

  return deadlines;
};

const buildIHDeadlines = (event: CalendarEvent): NewCalendarEvent[] => {
  const deadlines: NewCalendarEvent[] = [];
  const hearingDate = new Date(event.startTime);

  // 30-day filing deadline for unrepresented, non-detained respondents
  if (!event.detained) {
    deadlines.push({
      organizationId: event.organizationId,
      eventType: "filing_deadline",
      status: "scheduled",
      title: `Filing Deadline — ${event.title}`,
      startTime: addDays(hearingDate, -30),
      clientId: event.clientId,
      caseId: event.caseId,
      assignedStaffId: event.assignedStaffId,
      teamId: event.teamId,
      isAutoGenerated: true,
      parentEventId: event.id,
      notes:
        "Auto-generated: filing deadline 30 days before Individual Hearing",
    });
  }

  // Judge-ordered document deadline
  if (event.judgeDeadlineType) {
    let deadlineDate: Date | null = null;

    if (event.judgeDeadlineType === "30_days_before") {
      deadlineDate = addDays(hearingDate, -30);
    } else if (event.judgeDeadlineType === "60_days_before") {
      deadlineDate = addDays(hearingDate, -60);
    } else if (
      event.judgeDeadlineType === "custom" &&
      event.customDeadlineDate
    ) {
      deadlineDate = new Date(event.customDeadlineDate);
    }

    if (deadlineDate) {
      deadlines.push({
        organizationId: event.organizationId,
        eventType: "filing_deadline",
        status: "scheduled",
        title: `Judge-Ordered Document Deadline — ${event.title}`,
        startTime: deadlineDate,
        clientId: event.clientId,
        caseId: event.caseId,
        assignedStaffId: event.assignedStaffId,
        teamId: event.teamId,
        isAutoGenerated: true,
        parentEventId: event.id,
        notes: "Auto-generated: judge-ordered document deadline (IH rule)",
      });
    }
  }

  // 60-day scheduling order from removability finding date
  if (event.removabilityFindingDate) {
    const findingDate = new Date(event.removabilityFindingDate);
    deadlines.push({
      organizationId: event.organizationId,
      eventType: "filing_deadline",
      status: "scheduled",
      title: `Scheduling Order Deadline — ${event.title}`,
      startTime: addDays(findingDate, 60),
      clientId: event.clientId,
      caseId: event.caseId,
      assignedStaffId: event.assignedStaffId,
      teamId: event.teamId,
      isAutoGenerated: true,
      parentEventId: event.id,
      notes:
        "Auto-generated: scheduling order deadline 60 days from removability finding",
    });
  }

  return deadlines;
};

const insertDeadlines = async (event: CalendarEvent): Promise<void> => {
  let deadlines: NewCalendarEvent[] = [];

  if (event.eventType === "master_calendar_hearing") {
    deadlines = buildMCHDeadlines(event);
  } else if (event.eventType === "individual_hearing") {
    deadlines = buildIHDeadlines(event);
  }

  if (deadlines.length) {
    await db.insert(calendarEvents).values(deadlines);
  }
};

const deleteAutoGeneratedChildren = async (parentId: string): Promise<void> => {
  await db
    .delete(calendarEvents)
    .where(
      and(
        eq(calendarEvents.parentEventId, parentId),
        eq(calendarEvents.isAutoGenerated, true),
      ),
    );
};

// ─── Shared: fetch a single event with joins ─────────────────────────────────

const fetchEventWithJoins = async (
  id: string,
  organizationId: string,
) => {
  const rows = await db
    .select({
      id: calendarEvents.id,
      eventType: calendarEvents.eventType,
      status: calendarEvents.status,
      title: calendarEvents.title,
      startTime: calendarEvents.startTime,
      endTime: calendarEvents.endTime,
      location: calendarEvents.location,
      zoomLink: calendarEvents.zoomLink,
      notes: calendarEvents.notes,
      isAutoGenerated: calendarEvents.isAutoGenerated,
      parentEventId: calendarEvents.parentEventId,
      teamId: calendarEvents.teamId,
      clientId: clients.id,
      clientDisplayName: clients.displayName,
      caseId: cases.id,
      caseNumber: cases.caseNumber,
      staffId: staff.id,
      staffFirstName: staff.firstName,
      staffLastName: staff.lastName,
      staffRole: staff.jobTitle,
      leadId: leads.id,
      leadFirstName: leads.firstName,
      leadLastName: leads.lastName,
    })
    .from(calendarEvents)
    .leftJoin(clients, eq(clients.id, calendarEvents.clientId))
    .leftJoin(cases, eq(cases.id, calendarEvents.caseId))
    .leftJoin(staff, eq(staff.id, calendarEvents.assignedStaffId))
    .leftJoin(leads, eq(leads.id, calendarEvents.leadId))
    .where(
      and(
        eq(calendarEvents.id, id),
        eq(calendarEvents.organizationId, organizationId),
      ),
    );

  const [row] = rows;
  if (!row) return null;

  return {
    id: row.id,
    eventType: row.eventType,
    status: row.status,
    title: row.title,
    startTime: row.startTime,
    endTime: row.endTime,
    location: row.location,
    zoomLink: row.zoomLink,
    notes: row.notes,
    isAutoGenerated: row.isAutoGenerated,
    parentEventId: row.parentEventId,
    teamId: row.teamId,
    client: row.clientId
      ? { id: row.clientId, name: row.clientDisplayName ?? "" }
      : null,
    case: row.caseId
      ? { id: row.caseId, caseNumber: row.caseNumber ?? "" }
      : null,
    assignedStaff: row.staffId
      ? {
          id: row.staffId,
          name: `${row.staffFirstName} ${row.staffLastName}`,
          role: row.staffRole,
        }
      : null,
    lead: row.leadId
      ? {
          id: row.leadId,
          name: `${row.leadFirstName} ${row.leadLastName}`,
        }
      : null,
  };
};

